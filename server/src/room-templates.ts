/** id 의 템플릿 — 없거나 모르는 id 면 기본(광장). 방을 만드는 hello 가 무엇을 실어 와도 방은 생긴다 */
export function templateFor(id: string | undefined): RoomTemplate {
  return ROOM_TEMPLATES.find((t) => t.id === id) ?? DEFAULT_TEMPLATE;
}
