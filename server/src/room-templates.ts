export interface RoomTemplate {
  /** hello{map}·welcome{map} 에 오가는 값 — MAP_ID_RE 형식 */
  readonly id: string;
  /** 「로비 만들기」 맵 고르기에 보이는 이름 */
  readonly name: string;
  readonly room: RoomData;
}

export const DEFAULT_TEMPLATE: RoomTemplate = { id: 'plaza', name: '광장', room: DEFAULT_ROOM };

/** 맵 고르기 순서 그대로 — 첫 번째가 기본 */
export const ROOM_TEMPLATES: readonly RoomTemplate[] = [
  DEFAULT_TEMPLATE,
  { id: 'forest', name: '숲길', room: FOREST_ROOM },
  { id: 'court', name: '작은 마당', room: COURT_ROOM },
];

/** id 의 템플릿 — 없거나 모르는 id 면 기본(광장). 방을 만드는 hello 가 무엇을 실어 와도 방은 생긴다 */
export function templateFor(id: string | undefined): RoomTemplate {
  return ROOM_TEMPLATES.find((t) => t.id === id) ?? DEFAULT_TEMPLATE;
}
